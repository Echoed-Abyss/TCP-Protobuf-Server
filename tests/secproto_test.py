# T1: Normal flow - handshake, data, heartbeat, close
# ---------------------------------------------------------------------------
def test_t1_normal_flow():
    name = "T1 Normal flow (handshake + data + heartbeat + close)"
    try:
        srv_pub = get_pubkey_hex(SERVER_KEY)
        cli = SecureClient(HOST, SERVER_PORT, peer_pubkey=bytes.fromhex(srv_pub))
        cli.connect()
        cli.handshake()

        # Bidirectional data exchange (server echoes).
        for msg in [b"hello", b"world", b"secproto"]:
            cli.send_data(msg)
            resp = cli.recv_data()
            assert resp == msg, f"echo mismatch: got {resp!r} want {msg!r}"

        # Heartbeat: server sends heartbeat every 15s by default. We verify
        # the connection stays healthy by doing another round-trip after a
        # short delay (no 15s wait needed - the heartbeat is passive).
        time.sleep(0.5)
        cli.send_data(b"after-wait")
        resp = cli.recv_data()
        assert resp == b"after-wait"

        cli.close()
        record(name, True)
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


