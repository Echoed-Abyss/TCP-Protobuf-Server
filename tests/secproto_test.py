# T2: Tampering test - flip 1 bit in ciphertext, expect AEAD failure
# ---------------------------------------------------------------------------
def test_t2_tampering():
    name = "T2 Ciphertext tampering (AEAD auth failure + generic error)"
    try:
        srv_pub = get_pubkey_hex(SERVER_KEY)
        cli = SecureClient(HOST, SERVER_PORT, peer_pubkey=bytes.fromhex(srv_pub))
        cli.connect()
        cli.handshake()

        # Build a valid encrypted data frame.
        frame_bytes = cli.build_encrypted_frame_bytes(MSG_DATA, b"tamper-me")

        # Flip the last bit of the ciphertext (in the payload, past the header).
        tampered = bytearray(frame_bytes)
        tampered[-1] ^= 0x01
        tampered = bytes(tampered)

        # Send tampered frame. The server must reject and close.
        cli.send_raw_frame(tampered)

        # The next read should fail (connection closed by server after AEAD
        # failure). We expect either a recv error or a connection close.
        try:
            # Try to read; server should have closed the connection.
            data = cli.sock.recv(4096)
            # If we get data, it's likely the server's close. If empty, closed.
            # Either way, the tampered frame was not accepted.
            assert not data or len(data) == 0, "server accepted tampered frame"
            record(name, True, "connection closed after tampered frame (AEAD failed)")
        except (ConnectionError, OSError):
            record(name, True, "connection closed after tampered frame (AEAD failed)")

        cli.close()
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


