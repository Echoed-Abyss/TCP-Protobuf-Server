"""
secproto_test.py - Black-box / gray-box attack test suite for the secproto
secure TCP server.

Implements T1-T8 scenarios against the Go server binary. The tests do NOT
rely on the Go server's internal structure; they speak the wire protocol
directly via secproto_client.py.

Usage:
    pip install -r requirements.txt
    export SECPROTO_BIN=./build/secproto-linux-amd64   # or path to binary
    python3 secproto_test.py

All diagnostic output (AEAD failure / replay / expired / signature failure)
is printed LOCALLY by this script. The server must never return these
details - it returns only the generic "protocol error" and closes the
connection.
"""
