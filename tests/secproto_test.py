# T7: Concurrency stress - multiple connections, no seq/key cross-talk
# ---------------------------------------------------------------------------
def test_t7_concurrency():
    name = "T7 Concurrent connections (seq/key isolation)"
    try:
        srv_pub = bytes.fromhex(get_pubkey_hex(SERVER_KEY))
        errors = []
        lock = threading.Lock()

        def worker(i):
            try:
                cli = SecureClient(HOST, SERVER_PORT, peer_pubkey=srv_pub)
                cli.connect()
                cli.handshake()
                for j in range(5):
                    msg = f"conn{i}-msg{j}".encode()
                    cli.send_data(msg)
                    resp = cli.recv_data()
                    assert resp == msg, f"echo mismatch: {resp!r} != {msg!r}"
                cli.close()
            except Exception as e:
                with lock:
                    errors.append(f"worker {i}: {type(e).__name__}: {e}")

        threads = [threading.Thread(target=worker, args=(i,))
                   for i in range(8)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=15)

        if errors:
            record(name, False, "; ".join(errors[:3]))
        else:
            record(name, True, "all 8 concurrent connections succeeded")
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


