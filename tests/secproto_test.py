# T8: Reconnect - mid-handshake disconnect and mid-data reconnect
# ---------------------------------------------------------------------------
def test_t8_reconnect():
    name = "T8 Reconnect after disconnect (state cleanup + renegotiation)"
    try:
        srv_pub = bytes.fromhex(get_pubkey_hex(SERVER_KEY))

        # Part A: Normal connection, abrupt close, reconnect.
        cli = SecureClient(HOST, SERVER_PORT, peer_pubkey=srv_pub)
        cli.connect()
        cli.handshake()
        cli.send_data(b"first")
        assert cli.recv_data() == b"first"
        # Abrupt close (no close frame).
        cli.sock.close()
        time.sleep(0.2)

        # Reconnect with a fresh session.
        cli2 = SecureClient(HOST, SERVER_PORT, peer_pubkey=srv_pub)
        cli2.connect()
        cli2.handshake()
        cli2.send_data(b"second")
        assert cli2.recv_data() == b"second"
        cli2.close()

        # Part B: Disconnect mid-handshake, then reconnect cleanly.
        cli3 = SecureClient(HOST, SERVER_PORT, peer_pubkey=srv_pub)
        cli3.connect()
        # Send ClientHello only, then close before completing handshake.
        cli3.sock.close()
        time.sleep(0.2)

        # Reconnect - must work (server cleaned up the half-handshake state).
        cli4 = SecureClient(HOST, SERVER_PORT, peer_pubkey=srv_pub)
        cli4.connect()
        cli4.handshake()
        cli4.send_data(b"after-mid-hs-disconnect")
        assert cli4.recv_data() == b"after-mid-hs-disconnect"
        cli4.close()

        record(name, True, "reconnect succeeded after abrupt and mid-handshake disconnects")
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


