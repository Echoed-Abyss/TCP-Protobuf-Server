def gen_identity(path):
    """Run secproto genkey to produce an Ed25519 identity seed file."""
    subprocess.run(
        [SECPROTO_BIN, "-role", "genkey", "-key", path],
        check=True, capture_output=True,
    )


def get_pubkey_hex(path):
    """Extract the public key hex printed by genkey.

    Re-runs genkey? No - we parse the file? Simpler: call genkey with a
    temp output and grep. Actually we can just read the seed and derive
    the pubkey, but easier: run genkey once to a known path and capture
    stdout. We assume the key file already exists; re-derive pub from seed
    using cryptography.
    """
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey,
    )
    from cryptography.hazmat.primitives import serialization
    with open(path, "rb") as f:
        seed = f.read()
    priv = Ed25519PrivateKey.from_private_bytes(seed)
    pub = priv.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    return pub.hex()


def start_server(trust_store=None, extra_env=None):
    """Start the secproto server and return the Popen object."""
    env = os.environ.copy()
    if extra_env:
        env.update(extra_env)
    cmd = [
        SECPROTO_BIN, "-role", "server",
        "-key", SERVER_KEY,
        "-addr", f"{HOST}:{SERVER_PORT}",
    ]
    if trust_store:
        cmd += ["-trust-store", trust_store]
    proc = subprocess.Popen(cmd, env=env, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT)
    # Wait for the "listening" line.
    deadline = time.time() + 5
    while time.time() < deadline:
        line = proc.stdout.readline()
        if not line:
            time.sleep(0.1)
            continue
        if b"listening on" in line:
            return proc
    proc.kill()
    raise RuntimeError("server did not start listening in time")


def stop_server(proc):
    if proc and proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()


def ensure_keys():
    """Generate identity key files if they don't exist."""
    for path in (SERVER_KEY, CLIENT_KEY, ATTACKER_KEY):
        if not os.path.exists(path):
            gen_identity(path)


# ---------------------------------------------------------------------------
# Result reporting
# ---------------------------------------------------------------------------
def record(name, passed, detail=""):
    status = "PASS" if passed else "FAIL"
    results.append((name, passed, detail))
    print(f"[{status}] {name}" + (f" - {detail}" if detail else ""))


def summary():
    passed = sum(1 for _, p, _ in results if p)
    total = len(results)
    print("\n" + "=" * 60)
    print(f"RESULTS: {passed}/{total} tests passed")
    print("=" * 60)
    for name, p, detail in results:
        if not p:
            print(f"  FAIL: {name}: {detail}")
    return passed == total


