# T3: Replay test - resend a processed frame, expect replay window rejection
# ---------------------------------------------------------------------------
def test_t3_replay():
    name = "T3 Replay attack (seq window rejection)"
    try:
        srv_pub = get_pubkey_hex(SERVER_KEY)
        cli = SecureClient(HOST, SERVER_PORT, peer_pubkey=bytes.fromhex(srv_pub))
        cli.connect()
        cli.handshake()

        # Send a valid data frame and capture its raw bytes.
        frame_bytes = cli.build_encrypted_frame_bytes(MSG_DATA, b"replay-me")
        cli.send_raw_frame(frame_bytes)
        # Consume the echo.
        echo = cli.recv_data()
        assert echo == b"replay-me"

        # Now replay the exact same frame bytes.
        cli.send_raw_frame(frame_bytes)

        # Server should reject (replay) and close.
        try:
            data = cli.sock.recv(4096)
            assert not data, "server accepted replayed frame"
            record(name, True, "replay rejected (connection closed)")
        except (ConnectionError, OSError):
            record(name, True, "replay rejected (connection closed)")

        cli.close()
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


