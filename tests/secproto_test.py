# T5: MITM test - client pins real server key, MITM presents attacker key
# ---------------------------------------------------------------------------
def run_mitm_proxy(real_host, real_port, listen_port, attacker_identity,
                   stop_event):
    """A MITM proxy that replaces the server's identity pubkey in ServerHello.

    The client pins the real server's key. When it sees the attacker's key,
    the trust check (TOFU / pin) must fail and the handshake is rejected.
    """
    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind((HOST, listen_port))
    listener.listen(1)
    listener.settimeout(5)

    try:
        client_sock, _ = listener.accept()
    except socket.timeout:
        return

    try:
        # Connect to the real server.
        server_sock = socket.create_connection((real_host, real_port))

        def forward(src, dst, modify_serverhello=False):
            try:
                while not stop_event.is_set():
                    data = src.recv(65536)
                    if not data:
                        break
                    if modify_serverhello:
                        data = _replace_server_identity(data, attacker_identity)
                    dst.sendall(data)
            except (ConnectionError, OSError):
                pass

        # Client -> Server (forward ClientHello as-is)
        t1 = threading.Thread(target=forward, args=(client_sock, server_sock),
                              daemon=True)
        # Server -> Client (modify ServerHello identity pubkey)
        t2 = threading.Thread(target=forward,
                              args=(server_sock, client_sock, True),
                              daemon=True)
        t1.start()
        t2.start()
        t1.join(timeout=10)
        t2.join(timeout=10)
    finally:
        try:
            client_sock.close()
        except Exception:
            pass
        try:
            server_sock.close()
        except Exception:
            pass
    listener.close()


def _replace_server_identity(data, attacker_pubkey):
    """Find the ServerHello frame in `data` and replace server_identity_pubkey
    (protobuf field 5, bytes) with the attacker's 32-byte pubkey.

    This is a wire-level MITM. The signature in ServerProof is over the
    original transcript, so even if the client didn't pin the key, the
    signature check would fail. With pinning, the trust check fails first.
    """
    # data may contain one or more frames. Parse frame-by-frame.
    out = bytearray()
    pos = 0
    while pos + HEADER_SIZE <= len(data):
        length = struct.unpack(">I", data[pos + 33:pos + 37])[0]
        frame_end = pos + HEADER_SIZE + length
        if frame_end > len(data):
            # Incomplete frame; copy the rest as-is.
            out.extend(data[pos:])
            break
        frame = data[pos:frame_end]
        msg_type = frame[3]
        if msg_type == 2:  # MSG_SERVER_HELLO
            payload = bytearray(frame[HEADER_SIZE:])
            new_payload = _replace_proto_bytes_field(payload, 5, attacker_pubkey)
            # Rebuild frame with new length.
            new_frame = bytearray(frame[:HEADER_SIZE])
            struct.pack_into(">I", new_frame, 33, len(new_payload))
            new_frame.extend(new_payload)
            out.extend(new_frame)
        else:
            out.extend(frame)
        pos = frame_end
    return bytes(out)


def _replace_proto_bytes_field(payload, field_num, new_value):
    """Replace a length-delimited (wire type 2) field in a protobuf message.

    Returns the modified payload bytes. If the field is not found, appends it.
    """
    import secproto_client as sp
    fields = sp._parse_fields(payload)
    out = bytearray()
    replaced = False
    for fn, wt, val in fields:
        if fn == field_num and wt == 2:
            out.extend(sp._encode_bytes_field(field_num, new_value))
            replaced = True
        else:
            if wt == 0:
                out.extend(sp._encode_varint_field(fn, val))
            elif wt == 2:
                out.extend(sp._encode_bytes_field(fn, val))
            elif wt == 5:
                out.extend(sp._field_key(fn, wt) + val)
    if not replaced:
        out.extend(sp._encode_bytes_field(field_num, new_value))
    return bytes(out)


def test_t5_mitm():
    name = "T5 MITM attack (identity pin / signature rejection)"
    try:
        srv_pub = bytes.fromhex(get_pubkey_hex(SERVER_KEY))
        # Attacker identity (different from server).
        from cryptography.hazmat.primitives.asymmetric.ed25519 import (
            Ed25519PrivateKey,
        )
        from cryptography.hazmat.primitives import serialization
        with open(ATTACKER_KEY, "rb") as f:
            attacker_seed = f.read()
        attacker_priv = Ed25519PrivateKey.from_private_bytes(attacker_seed)
        attacker_pub = attacker_priv.public_key().public_bytes(
            encoding=serialization.Encoding.Raw,
            format=serialization.PublicFormat.Raw,
        )

        stop_event = threading.Event()
        mitm_thread = threading.Thread(
            target=run_mitm_proxy,
            args=(HOST, SERVER_PORT, MITM_PORT, attacker_pub, stop_event),
            daemon=True,
        )
        mitm_thread.start()
        time.sleep(0.5)

        # Client connects to the MITM proxy, pinning the REAL server key.
        cli = SecureClient(HOST, MITM_PORT, peer_pubkey=srv_pub)
        cli.connect()

        # Handshake should fail: the ServerHello carries the attacker's key,
        # which does not match the pinned server key.
        handshake_failed = False
        try:
            cli.handshake()
        except Exception:
            handshake_failed = True

        stop_event.set()
        cli.close()

        assert handshake_failed, "handshake should fail against MITM with wrong identity key"
        record(name, True, "MITM rejected (pinned key mismatch / signature would fail)")
    except Exception as e:
        record(name, False, f"{type(e).__name__}: {e}")
        traceback.print_exc()


